from __future__ import annotations

import json
from typing import Any, Dict, List


PLANNER_DECOMPOSE_SYSTEM = """\
You are an experienced expert in multi-hop open-domain question answering and an exam question designer. Your role is to break a challenging question into a small series of simpler, high-level sub-questions.

Each sub-question must build on earlier sub-questions so that solving all of them is sufficient to answer the original question. Do not create overly detailed steps. Generate 2 to 5 ordered sub-questions, with fewer for easy questions and more for challenging questions. A hint should state what answering that sub-question will establish, without answering it. Do not retrieve information, solve the question, reveal hidden reasoning, or give the final answer.

Return only one JSON object with this schema:
{"subquestions":[{"subquestion":"...","hint":"..."}]}
"""


def planner_decompose_user(question: str) -> str:
    return (
        "Question: "
        + question
        + "\nGenerate the ordered decomposition now. Return JSON only."
    )


PLANNER_EVALUATE_SYSTEM = """\
You are an experienced expert in multi-hop open-domain question answering and an exam question designer. Evaluate the overall difficulty and the difficulty and credit of the provided sub-questions.

Difficulty is an integer from 1 (easiest) to 5 (hardest). Consider conceptual depth, number of relations or entities that must be connected, required external knowledge, and potential for misdirection. Keep the supplied sub-questions unchanged and do not add any. Assign every sub-question a positive integer credit. Credits must sum exactly to 100.

Return only one JSON object with this schema:
{
  "problem":{"reason":"brief concrete justification","evaluated_level":1},
  "subquestions":[
    {"index":1,"reason":"brief concrete justification","evaluated_level":1,"credit":50}
  ]
}

Every reason must explain the assigned level in no more than 50 words. Never copy
the schema placeholders "brief concrete justification" or "at most 50 words".
"""


def planner_evaluate_user(question: str, subquestions: List[Dict[str, str]]) -> str:
    return (
        "Question: "
        + question
        + "\nSub-questions:\n"
        + json.dumps(subquestions, ensure_ascii=False, indent=2)
        + "\nEvaluate them now. Return JSON only."
    )


REASONER_SYSTEM = """\
You are Qwen3-8B solving one ordered sub-question within a Plan-and-Budget route for open-domain multi-hop QA. Work only on the current sub-question. You may use your own knowledge or request Wikipedia search results.

At each turn, choose exactly one action:
1. Search: <Search>one concise search query</Search>
2. Finish the current sub-question: <Subanswer>concise factual result</Subanswer><Cite>comma-separated document ids, or NONE</Cite>

Search queries must be generated by you from the current information. You may Search repeatedly when necessary. Never invent retrieved evidence. Do not output both Search and Subanswer in the same turn.

For the last sub-question, Finish with:
<Subanswer>concise result for this sub-question</Subanswer><FinalAnswer>short answer to the original question</FinalAnswer><Cite>comma-separated document ids, or NONE</Cite>

The FinalAnswer must contain only the answer, without explanation. The assigned sub-question budget is a soft target communicated through the prompt, not a hard generation cutoff. Try to complete Search requests and answers within that target, but always finish the selected tagged action. Be direct.
"""


def reasoner_user(
    *,
    original_question: str,
    level: int,
    total_budget: int,
    scheduler: str,
    subquestion_index: int,
    subquestion_count: int,
    subquestion: str,
    hint: str,
    subquestion_budget: int,
    actual_output_tokens_so_far: int,
    previous_summaries: List[Dict[str, Any]],
    search_rounds: List[Dict[str, Any]],
    search_limit_reached: bool,
) -> str:
    if previous_summaries:
        previous = json.dumps(previous_summaries, ensure_ascii=False, indent=2)
    else:
        previous = "None."

    evidence_blocks: List[str] = []
    for round_row in search_rounds:
        docs = []
        for doc in round_row["documents"]:
            docs.append(
                f"[Doc id={doc['id']} rank={doc['rank']}]\n{doc['contents']}"
            )
        evidence_blocks.append(
            f"Search round {round_row['search_round']}\n"
            f"Query: {round_row['query']}\n"
            + "\n\n".join(docs)
        )
    evidence = "\n\n=====\n\n".join(evidence_blocks) or "None yet."

    action_constraint = (
        "The maximum number of Search actions has been reached. You MUST finish now; "
        "do not output another Search action."
        if search_limit_reached
        else "Choose Search or Finish naturally from the available information."
    )
    last_instruction = (
        "This is the last sub-question, so a Finish action MUST also include FinalAnswer."
        if subquestion_index == subquestion_count
        else "Do not answer the overall question unless this is needed in the subanswer."
    )

    return f"""\
Original question: {original_question}
Planner difficulty: {level}/5
Official total output budget: {total_budget} tokens
Scheduler: {scheduler}

Current sub-question: {subquestion_index}/{subquestion_count}
Sub-question: {subquestion}
Hint: {hint}
Soft output-budget target for this sub-question: {subquestion_budget} tokens
Actual output tokens used by earlier turns of this sub-question: {actual_output_tokens_so_far} tokens

The budget is advisory. Do not omit or leave a Search, Subanswer, Cite, or FinalAnswer tag unfinished merely to meet it.

Earlier sub-question answer summaries and cited document ids (no raw passages are carried across sub-questions):
{previous}

Raw Top-5 evidence accumulated only inside this sub-question:
{evidence}

{action_constraint}
{last_instruction}
Return exactly one tagged action.
"""
